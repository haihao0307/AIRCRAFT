import { readFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';
import vm from 'node:vm';
const read=(p)=>readFile(p,'utf8');
const manifest=JSON.parse(await read('data/aircraft/308bg/80-days-texture-master-v2.json'));
const qa=JSON.parse(await read('reports/80-days-texture-master-v2-browser-qa.json'));
const chunks=await Promise.all(Array.from({length:5},(_,i)=>read(`assets/livery/80-days/texture-master-v2/payload-${String(i).padStart(2,'0')}.txt`)));
const html=gunzipSync(Buffer.from(chunks.join('').replace(/\s+/g,''),'base64')).toString('utf8');
const loader=await read('80-days-texture-master-v2.html');
const assert=(c,m)=>{if(!c)throw new Error(m)};
assert(manifest.aircraft?.name==='“80 DAYS”','identity mismatch');
assert(manifest.aircraft?.serial==='42-73257','serial mismatch');
assert(manifest.aircraft?.aircraftNumber==='487','aircraft number mismatch');
assert(manifest.modelBinding==='not-started-by-design','model binding gate missing');
assert(manifest.visualAcceptance==='review-required','visual acceptance must remain review-required');
assert(manifest.historicalRules?.stam?.side==='starboard','STAM side mismatch');
assert(manifest.historicalRules?.victoryFlags?.starboard===8,'starboard flag count mismatch');
assert(manifest.historicalRules?.victoryFlags?.port===0,'port flag count mismatch');
assert(manifest.historicalRules?.bombMarks?.count===null,'bomb count must remain null');
assert(manifest.historicalRules?.bombMarks?.rendered===false,'bomb marks must remain absent');
for(const text of ['“80 DAYS”','STAM','ROBBY','HUFF','273257','487','Base Color','Normal','Roughness','Height','AO','Metallic','Decal Mask','LiveryUV'])assert(html.includes(text),`missing UI text ${text}`);
assert(manifest.historicalRules?.sourceLegacyMarksRendered===false,'legacy source marks must remain unrendered');
assert(html.includes('8K 终检')&&html.includes('8192'),'8K path missing');
assert(html.includes('战损位置缺少逐处照片证明'),'damage inference warning missing');
assert(!/GLTFLoader|\.glb["']/i.test(html),'model binding code is forbidden in texture master');
const scripts=[...html.matchAll(/<script(?:[^>]*)>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(s=>s.trim());
for(const [i,script] of scripts.entries())new vm.Script(script,{filename:`texture-master-inline-${i}.js`});
assert(loader.includes('DecompressionStream')&&loader.includes('texture-master-v2/payload-'),'loader contract missing');
assert(qa.ready===true&&qa.consoleErrors===0&&qa.pageErrors===0,'browser QA did not pass');
assert(qa.checks?.modelBindingNotStarted===true,'QA binding state mismatch');
assert(qa.delivery?.loaderBrowserQA?.status==='pass','loader browser QA missing');
console.log(`80 DAYS texture master V2 validated: ${html.length} chars, 5 payload parts.`);
console.log('Historical markings, 8K path, PBR channels, detail controls and pre-binding gate passed.');
